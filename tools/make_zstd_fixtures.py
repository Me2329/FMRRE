#!/usr/bin/env python3
"""Regenerates tests/zstd_fixtures.h: Zstandard frames made by the real zstd library (python-zstandard), for the
self-tests. Only the compressed bytes are stored (base64); the self-test makes the same plaintext with zText /
zNoise (the same generators as here) and compares.

Together they use every part of the format the decoder has (checked when this was written, block by block):
  A  log-like text, 140 kB, level 19, checksum, single segment: two blocks - Huffman literals, then treeless
     literals and FSE tables repeated from the first block (repeat mode)
  B  text, 30 kB, level 1, no checksum, no content size (windowed): 4-stream Huffman literals
  C  150 kB of zeros (RLE blocks) + a skippable frame + 2 kB of noise (a raw block) + 3 kB of text: four frames,
     predefined FSE tables
  E  3 kB of noise, a forced block end, then 'Z' + 24 bytes copied from the noise, 120 times: RLE literals and
     an RLE offset table
Needs the `zstandard` module (only here, not for the tests).
"""
import base64
import os

import zstandard as zs

PARTS = [b"boot", b"init_boot", b"vendor_boot", b"dtbo", b"vbmeta", b"system", b"vendor", b"product"]


def text(n, seed=1):
    x, out, i = seed, bytearray(), 0
    while len(out) < n:
        x = (x * 1103515245 + 12345) & 0x7FFFFFFF
        p = PARTS[(x >> 16) % len(PARTS)]
        out += b"flash %s_%s: block %d of %d ok\n" % (p, b"ab"[(x >> 20) & 1:((x >> 20) & 1) + 1], i % 8, 8)
        i += 1
    return bytes(out[:n])


def noise(n, seed=7):
    x, out = seed, bytearray()
    for _ in range(n):
        x = (x * 1103515245 + 12345) & 0x7FFFFFFF
        out.append((x >> 16) & 0xFF)
    return bytes(out)


def main():
    a = zs.ZstdCompressor(level=19, write_checksum=True).compress(text(140000))
    b = zs.ZstdCompressor(level=1, write_checksum=False, write_content_size=False).compress(text(30000, 5))
    c = (zs.ZstdCompressor(level=3, write_checksum=True).compress(bytes(150000)) + bytes.fromhex("502a4d1805000000") +
         b"skip!" + zs.ZstdCompressor(level=3).compress(noise(2000)) +
         zs.ZstdCompressor(level=6, write_checksum=True).compress(text(3000, 9)))
    nz = noise(3000, 11)
    co = zs.ZstdCompressor(level=3, write_checksum=True).compressobj()
    e = co.compress(nz) + co.flush(zs.COMPRESSOBJ_FLUSH_BLOCK)
    e += co.compress(b"".join(b"Z" + nz[k * 24:(k + 1) * 24] for k in range(120))) + co.flush()
    # what the self-test compares against, made by the reference decoder
    d = zs.ZstdDecompressor()
    assert d.decompress(a) == text(140000)
    assert d.decompressobj().decompress(b) == text(30000, 5)
    out = ["// Generated by tools/make_zstd_fixtures.py - frames made by the zstd library (base64).\n#pragma once\n\n"]
    for name, data in (("A", a), ("B", b), ("C", c), ("E", e)):
        b64 = base64.b64encode(data).decode()
        out.append("static const char kZst%s[] =\n%s;\n" % (name, "\n".join('    "%s"' % b64[i:i + 110] for i in range(0, len(b64), 110))))
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "zstd_fixtures.h")
    with open(path, "w") as f:
        f.write("".join(out))
    print("wrote", os.path.normpath(path), sum(len(x) for x in (a, b, c, e)), "bytes of frames")


if __name__ == "__main__":
    main()
