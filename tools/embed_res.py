#!/usr/bin/env python3
"""Embed resource files (fonts) into a C++ source file so the recovery binary
is completely self-contained (no /res or /twres dependency)."""
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files = [
    ("font_regular", "res/fonts/Inter-Regular.otf"),
    ("font_semibold", "res/fonts/Inter-SemiBold.otf"),
    ("font_bold", "res/fonts/Inter-Bold.otf"),
    ("font_mono", "res/fonts/DejaVuSansMono.ttf"),
]
out = os.path.join(root, "src/gfx/embedded_res.cpp")
with open(out, "w") as f:
    f.write("// AUTO-GENERATED by tools/embed_res.py - do not edit.\n")
    f.write('#include "gfx/embedded_res.h"\n\nnamespace tw::res {\n')
    for name, path in files:
        data = open(os.path.join(root, path), "rb").read()
        f.write(f"static const unsigned char k_{name}[{len(data)}] = {{\n")
        for i in range(0, len(data), 24):
            f.write("  " + ",".join(str(b) for b in data[i:i+24]) + ",\n")
        f.write("};\n")
        f.write(f"const Blob {name} = {{ k_{name}, {len(data)} }};\n\n")
    f.write("}  // namespace tw::res\n")
print("wrote", out)
