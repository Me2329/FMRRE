#!/usr/bin/env python3
"""Regenerates tests/sig_fixtures.h: small zips signed like signapk -w, for the self-tests.

New keys are made each time (openssl), so the output differs from run to run; the tests only depend on what
the fixtures are, not on their bytes:
  kSigRsa*  RSA-2048, sha256WithRSA certificate -> SHA-256 signature
  kSigEc*   EC P-256, ecdsa-with-SHA256
  kSigTest* the subject of AOSP's public test keys, sha1WithRSA certificate -> SHA-1 signature
  kSigE3*   RSA-2048 with e=3, sha1WithRSA certificate (the oldest Android OTA keys)
  kSigZip   the zip they all signed (unsigned)
  kSigResKeys  the same keys as a pre-Android-10 /res/keys (mincrypt format, computed here independently):
               v4 (Rsa), v5 (Ec), v2 (Test, words written as signed numbers like old dumpkey), v1 (E3)
Needs the `cryptography` module (only here, not for the tests).
"""
import io
import os
import subprocess
import sys
import tempfile
import zipfile

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests"))
import signapk  # noqa: E402


def c_array(name, data):
    rows = [",".join("0x%02x" % b for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    return "static const unsigned char %s[] = {\n    %s};\n" % (name, ",\n    ".join(rows))


def mincrypt_rsa(pub, version, signed_words=False):
    n = pub.public_numbers().n
    words = (n.bit_length() + 31) // 32
    n0inv = (-pow(n, -1, 1 << 32)) % (1 << 32)
    rr = pow(2, 64 * words, n)  # R^2 mod n, R = 2^(32*words)
    def w(x, i):
        v = (x >> (32 * i)) & 0xFFFFFFFF
        return v - (1 << 32) if signed_words and v >= 1 << 31 else v
    body = "{%d,0x%x,{%s},{%s}}" % (words, n0inv, ",".join(str(w(n, i)) for i in range(words)),
                                    ",".join(str(w(rr, i)) for i in range(words)))
    return body if version == 1 else "v%d %s" % (version, body)


def mincrypt_ec(pub):
    nums = pub.public_numbers()
    le = lambda v: ",".join(str(b) for b in v.to_bytes(32, "big")[::-1])
    return "v5 {32,{%s},{%s}}" % (le(nums.x), le(nums.y))


def main():
    from cryptography import x509 as cx509
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "sig_fixtures.h")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_STORED) as z:
        z.writestr(zipfile.ZipInfo("hello.txt", (2026, 1, 1, 0, 0, 0)), b"FMRRE signature test\n")
    plain = buf.getvalue()
    parts = ["// Generated by tools/make_sig_fixtures.py - zips signed like AOSP's signapk -w (keys made with openssl).\n",
             "#pragma once\n\n", c_array("kSigZip", plain)]
    pubs = {}
    with tempfile.TemporaryDirectory() as d:
        e3key = os.path.join(d, "e3.key")
        subprocess.run(["openssl", "genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:2048", "-pkeyopt",
                        "rsa_keygen_pubexp:3", "-out", e3key], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        for name, kind, subject, md in [
            ("Rsa", "rsa:2048", "/O=FMR Test/CN=FMR RSA test key", "sha256"),
            ("Ec", "ec", "/O=FMR Test/CN=FMR EC test key", "sha256"),
            ("Test", "rsa:2048", "/C=US/ST=California/L=Mountain View/O=Android/OU=Android/CN=Android/"
                                 "emailAddress=android@android.com", "sha1"),
            ("E3", None, "/CN=FMR e=3 test key", "sha1"),
        ]:
            if kind:
                cert, key = signapk.make_key(kind, subject, os.path.join(d, name), md)
            else:  # an existing key (e=3): just the certificate
                cert, key = os.path.join(d, name + ".pem"), e3key
                subprocess.run(["openssl", "req", "-x509", "-key", key, "-days", "36500", "-subj", subject, "-" + md,
                                "-out", cert], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            signed = signapk.sign_zip(plain, cert, key, md)
            with open(cert, "rb") as f:
                pem = f.read()
            pubs[name] = cx509.load_pem_x509_certificate(pem).public_key()
            parts.append(c_array("kSig%sZip" % name, signed))
            parts.append("static const char kSig%sCert[] =\n%s;\n" % (
                name, "\n".join('    "%s\\n"' % line for line in pem.decode().strip().split("\n"))))
    reskeys = ",\n".join([mincrypt_rsa(pubs["Rsa"], 4), mincrypt_ec(pubs["Ec"]), mincrypt_rsa(pubs["Test"], 2, True),
                          mincrypt_rsa(pubs["E3"], 1)])
    parts.append("static const char kSigResKeys[] =\n%s;\n" % "\n".join(
        '    "%s"' % reskeys[i:i + 100].replace("\n", "\\n") for i in range(0, len(reskeys), 100)))
    with open(out, "w") as f:
        f.write("".join(parts))
    print("wrote", os.path.normpath(out))


if __name__ == "__main__":
    main()
