#!/usr/bin/env python3
"""Regenerates tests/sig_fixtures.h: small zips signed like signapk -w, for the self-tests.

New keys are made each time (openssl), so the output differs from run to run; the tests only depend on what
the fixtures are, not on their bytes:
  kSigRsa*  RSA-2048, sha256WithRSA certificate -> SHA-256 signature
  kSigEc*   EC P-256, ecdsa-with-SHA256
  kSigTest* the subject of AOSP's public test keys, sha1WithRSA certificate -> SHA-1 signature
  kSigZip   the zip they all signed (unsigned)
"""
import io
import os
import sys
import tempfile
import zipfile

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests"))
import signapk  # noqa: E402


def c_array(name, data):
    rows = [",".join("0x%02x" % b for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    return "static const unsigned char %s[] = {\n    %s};\n" % (name, ",\n    ".join(rows))


def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "sig_fixtures.h")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_STORED) as z:
        z.writestr(zipfile.ZipInfo("hello.txt", (2026, 1, 1, 0, 0, 0)), b"FMRRE signature test\n")
    plain = buf.getvalue()
    parts = ["// Generated by tools/make_sig_fixtures.py - zips signed like AOSP's signapk -w (keys made with openssl).\n",
             "#pragma once\n\n", c_array("kSigZip", plain)]
    with tempfile.TemporaryDirectory() as d:
        for name, kind, subject, md in [
            ("Rsa", "rsa:2048", "/O=FMR Test/CN=FMR RSA test key", "sha256"),
            ("Ec", "ec", "/O=FMR Test/CN=FMR EC test key", "sha256"),
            ("Test", "rsa:2048", "/C=US/ST=California/L=Mountain View/O=Android/OU=Android/CN=Android/"
                                 "emailAddress=android@android.com", "sha1"),
        ]:
            cert, key = signapk.make_key(kind, subject, os.path.join(d, name), md)
            signed = signapk.sign_zip(plain, cert, key, md)
            with open(cert, "rb") as f:
                pem = f.read()
            parts.append(c_array("kSig%sZip" % name, signed))
            parts.append("static const char kSig%sCert[] =\n%s;\n" % (
                name, "\n".join('    "%s\\n"' % line for line in pem.decode().strip().split("\n"))))
    with open(out, "w") as f:
        f.write("".join(parts))
    print("wrote", os.path.normpath(out))


if __name__ == "__main__":
    main()
